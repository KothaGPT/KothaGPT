"""Optional reasoning auxiliary head for KothaGPT (WS-3).

A small supervised decoder head that predicts solution-step tokens from the
base model's hidden states. It is used during training for auxiliary
supervision and is *not* used at inference — chain-of-thought is generated by
the base LM head. The head is opt-in via ``ModelConfig.reasoning_head`` so
that reasoning-specialist SFT runs can add the auxiliary loss without changing
the base model's parameter count for non-reasoning checkpoints.
"""

from __future__ import annotations

import torch
import torch.nn.functional as F
from torch import nn

__all__ = ["ReasoningHead", "ReasoningHeadLoss"]


class ReasoningHead(nn.Module):
    """Supervised decoder head predicting solution-step tokens."""

    def __init__(
        self,
        hidden_size: int,
        vocab_size: int,
        *,
        num_layers: int = 2,
        intermediate_size: int | None = None,
        dropout: float = 0.0,
    ) -> None:
        super().__init__()
        if hidden_size <= 0:
            raise ValueError("hidden_size must be positive")
        if vocab_size <= 0:
            raise ValueError("vocab_size must be positive")
        if num_layers < 1:
            raise ValueError("num_layers must be at least 1")
        if not 0.0 <= dropout < 1.0:
            raise ValueError("dropout must be in [0, 1)")

        self.hidden_size = hidden_size
        self.vocab_size = vocab_size
        self.num_layers = num_layers
        self.dropout = dropout

        inter = intermediate_size or max(4 * hidden_size, hidden_size)
        layers: list[nn.Module] = []
        in_dim = hidden_size
        for _ in range(num_layers - 1):
            layers.append(nn.Linear(in_dim, inter))
            layers.append(nn.GELU())
            if dropout > 0:
                layers.append(nn.Dropout(dropout))
            in_dim = inter
        layers.append(nn.Linear(in_dim, vocab_size))
        self.net = nn.Sequential(*layers)

    def forward(self, hidden_states: torch.Tensor) -> torch.Tensor:
        """Project hidden states to per-token logits over the solution-step vocab.

        Args:
            hidden_states: tensor of shape (batch, seq, hidden_size).

        Returns:
            tensor of shape (batch, seq, vocab_size).
        """
        if hidden_states.dim() != 3:
            raise ValueError(
                f"hidden_states must be 3D (batch, seq, hidden), got shape {tuple(hidden_states.shape)}"
            )
        return self.net(hidden_states)


class ReasoningHeadLoss:
    """Cross-entropy loss over solution-step targets with label smoothing."""

    def __init__(self, label_smoothing: float = 0.0) -> None:
        if not 0.0 <= label_smoothing < 1.0:
            raise ValueError("label_smoothing must be in [0, 1)")
        self.label_smoothing = label_smoothing

    def __call__(
        self,
        logits: torch.Tensor,
        targets: torch.Tensor,
        ignore_index: int = -100,
    ) -> torch.Tensor:
        if logits.dim() != 3:
            raise ValueError(f"logits must be 3D, got shape {tuple(logits.shape)}")
        if targets.dim() != 2:
            raise ValueError(f"targets must be 2D, got shape {tuple(targets.shape)}")
        batch, seq, vocab = logits.shape
        if targets.shape != (batch, seq):
            raise ValueError(
                f"targets shape {tuple(targets.shape)} incompatible with logits {(batch, seq, vocab)}"
            )
        # Flatten for cross_entropy (ignore padding positions).
        flat_logits = logits.reshape(-1, vocab)
        flat_targets = targets.reshape(-1)
        return F.cross_entropy(
            flat_logits,
            flat_targets,
            ignore_index=ignore_index,
            label_smoothing=self.label_smoothing,
        )


def _smoke() -> None:
    head = ReasoningHead(hidden_size=16, vocab_size=32, num_layers=2)
    hidden = torch.randn(2, 5, 16)
    logits = head(hidden)
    assert logits.shape == (2, 5, 32)
    loss_fn = ReasoningHeadLoss()
    targets = torch.randint(0, 32, (2, 5))
    loss = loss_fn(logits, targets)
    assert loss.dim() == 0 and loss.item() >= 0.0
    loss.backward()
    assert head.net[-1].weight.grad is not None


if __name__ == "__main__":
    _smoke()
    print("reasoning head ok")